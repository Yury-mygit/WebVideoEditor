const IMG = (name: string) => `/guide/${name}`;
const DEMO = (name: string) => `/guide/demo/${name}`;

function Shot({ src, alt, legend, narrow, side }: { src: string; alt: string; legend?: ReactNode[]; narrow?: boolean; side?: boolean }) {
  return (
    <figure className={`guide-shot ${narrow ? 'narrow' : ''} ${side ? 'side' : ''}`}>
      <a href={IMG(src)} target="_blank" rel="noreferrer" title="Открыть в полном размере">
        <img src={IMG(src)} alt={alt} loading="lazy" />
      </a>
      {legend && (
        <ol className="guide-legend">
          {legend.map((item, i) => (
            <li key={i}>
              <span className="guide-num">{i + 1}</span>
              <span>{item}</span>
            </li>
          ))}
        </ol>
      )}
    </figure>
  );
}

function Step({ id, n, title, children }: { id: string; n: number; title: string; children: ReactNode }) {
  return (
    <section id={id} className="guide-step">
      <h2>
        <span className="guide-step-num">{n}</span>
        {title}
      </h2>
      {children}
    </section>
  );
}

